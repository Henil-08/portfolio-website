// Bakes a few of Bruno Simon's folio-2025 props (MIT, (c) 2025 Bruno Simon) into
// components/world/models/props/brunoProps.ts, so they need no loader or Suspense.
// Each prop is one mesh in his .glb, flat-shaded off his palette texture: the
// palette pixel under each vertex's UV becomes a vertex colour.
// usage: node scripts/bake-bruno.mjs <folio-2025 checkout>
// The source .glb files and his LICENSE live in public/bruno/props/.
import { readFileSync, writeFileSync, copyFileSync, mkdirSync } from "node:fs";
import { join } from "node:path";
import draco3d from "draco3d";
import sharp from "sharp";

const repo = process.argv[2];
if (!repo) throw new Error("usage: node scripts/bake-bruno.mjs <folio-2025 checkout>");

// [export name, glb, mesh index, uniform scale (his node scale)]
const PROPS = [
  ["BENCH", "benches/benches.glb", 0, 1.092],
  ["LANTERN", "lanterns/lanterns.glb", 0, 1],
  ["LANTERN_LIGHT", "lanterns/lanterns.glb", 1, 1],
  ["FENCE", "fences/fences.glb", 1, 1],
];

const decoder = await draco3d.createDecoderModule({});

function parse(file) {
  const d = readFileSync(file);
  const jsonLen = d.readUInt32LE(12);
  const json = JSON.parse(d.subarray(20, 20 + jsonLen).toString());
  const binStart = 20 + jsonLen + 8;
  const bin = d.subarray(binStart, binStart + d.readUInt32LE(20 + jsonLen));
  return { json, bin };
}

function view(g, i) {
  const bv = g.json.bufferViews[i];
  return g.bin.subarray(bv.byteOffset ?? 0, (bv.byteOffset ?? 0) + bv.byteLength);
}

function accessor(g, i) {
  const a = g.json.accessors[i];
  const n = { SCALAR: 1, VEC2: 2, VEC3: 3, VEC4: 4 }[a.type];
  const buf = view(g, a.bufferView);
  const off = a.byteOffset ?? 0;
  const T = { 5126: Float32Array, 5123: Uint16Array, 5125: Uint32Array, 5121: Uint8Array }[a.componentType];
  const out = new T(a.count * n);
  const stride = g.json.bufferViews[a.bufferView].byteStride ?? n * T.BYTES_PER_ELEMENT;
  for (let k = 0; k < a.count; k++)
    for (let c = 0; c < n; c++) out[k * n + c] = new T(buf.buffer.slice(buf.byteOffset + off + k * stride + c * T.BYTES_PER_ELEMENT, buf.byteOffset + off + k * stride + (c + 1) * T.BYTES_PER_ELEMENT))[0];
  return Array.from(out);
}

function dracoPrim(g, prim) {
  const ext = prim.extensions.KHR_draco_mesh_compression;
  const buf = view(g, ext.bufferView);
  const dec = new decoder.Decoder();
  const db = new decoder.DecoderBuffer();
  db.Init(new Int8Array(buf.buffer, buf.byteOffset, buf.byteLength), buf.byteLength);
  const mesh = new decoder.Mesh();
  const st = dec.DecodeBufferToMesh(db, mesh);
  if (!st.ok()) throw new Error(st.error_msg());
  const read = (id, n) => {
    const att = dec.GetAttributeByUniqueId(mesh, id);
    const arr = new decoder.DracoFloat32Array();
    dec.GetAttributeFloatForAllPoints(mesh, att, arr);
    const out = [];
    for (let i = 0; i < mesh.num_points() * n; i++) out.push(arr.GetValue(i));
    decoder.destroy(arr);
    return out;
  };
  const a = ext.attributes;
  const position = read(a.POSITION, 3);
  const normal = read(a.NORMAL, 3);
  const uv = a.TEXCOORD_0 !== undefined ? read(a.TEXCOORD_0, 2) : null;
  const ia = new decoder.DracoUInt32Array();
  const index = [];
  for (let f = 0; f < mesh.num_faces(); f++) {
    dec.GetFaceFromMesh(mesh, f, ia);
    index.push(ia.GetValue(0), ia.GetValue(1), ia.GetValue(2));
  }
  decoder.destroy(ia);
  decoder.destroy(mesh);
  decoder.destroy(db);
  decoder.destroy(dec);
  return { position, normal, uv, index };
}

async function palette(g) {
  const img = g.json.images[0];
  const png = view(g, img.bufferView);
  const { data, info } = await sharp(png).raw().ensureAlpha().toBuffer({ resolveWithObject: true });
  return (u, v) => {
    const x = Math.min(info.width - 1, Math.max(0, Math.floor(u * info.width)));
    const y = Math.min(info.height - 1, Math.max(0, Math.floor(v * info.height))); // glTF uv: v down from the top row
    const i = (y * info.width + x) * 4;
    return [data[i], data[i + 1], data[i + 2]];
  };
}

const r3 = (v) => Math.round(v * 1000) / 1000;
let out = `// Generated by scripts/bake-bruno.mjs from Bruno Simon's folio-2025 (MIT, (c) 2025 Bruno Simon):
// static/{benches,lanterns,fences}/*.glb. position / normal in metres (origin at the
// prop's centre, as in his files), color = his palette pixel under each vertex (sRGB 0-255).
// The source .glb files are kept in public/bruno/props/ next to his LICENSE.md.

export type PropModel = { position: number[]; normal: number[]; color: number[]; index: number[] };
`;
mkdirSync("public/bruno/props", { recursive: true });
for (const [name, file, meshIndex, scale] of PROPS) {
  const g = parse(join(repo, "static", file));
  copyFileSync(join(repo, "static", file), join("public/bruno/props", file.split("/")[1]));
  const prim = g.json.meshes[meshIndex].primitives[0];
  const p = prim.extensions?.KHR_draco_mesh_compression
    ? dracoPrim(g, prim)
    : {
        position: accessor(g, prim.attributes.POSITION),
        normal: accessor(g, prim.attributes.NORMAL),
        uv: prim.attributes.TEXCOORD_0 !== undefined ? accessor(g, prim.attributes.TEXCOORD_0) : null,
        index: accessor(g, prim.indices),
      };
  const mat = g.json.materials?.[prim.material];
  const pick = p.uv && g.json.images?.length ? await palette(g) : null;
  const color = [];
  for (let k = 0; k < p.position.length / 3; k++) {
    if (pick && mat?.name === "palette") color.push(...pick(p.uv[k * 2], p.uv[k * 2 + 1]));
    else color.push(255, 255, 255); // emissive parts: coloured at runtime
  }
  out += `
export const ${name}: PropModel = {
  position: [${p.position.map((v) => r3(v * scale)).join(",")}],
  normal: [${p.normal.map(r3).join(",")}],
  color: [${color.join(",")}],
  index: [${p.index.join(",")}],
};
`;
  console.log(name, p.position.length / 3, "vertices", p.index.length / 3, "triangles");
}
writeFileSync("components/world/models/props/brunoProps.ts", out);
